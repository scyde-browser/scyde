// Bundles web/packages/i18n locales into strings.js so file:// prototypes can read them without fetch.
// Run: node design/prototypes/_shared/build-strings.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const loc = (l) => JSON.parse(readFileSync(path.resolve(here, `../../../web/packages/i18n/locales/${l}.json`), 'utf8'));
writeFileSync(
  path.join(here, 'strings.js'),
  `// Generated by build-strings.mjs from web/packages/i18n. Do not edit.\nwindow.SCYDE_STRINGS = ${JSON.stringify({ hr: loc('hr'), en: loc('en') }, null, 1)};\n`,
);
console.log('strings.js written');
