// Aura tokens build: design/tokens (DTCG) -> CSS custom properties, Kotlin (Compose), Swift (SwiftUI), flat JSON.
// Style Dictionary resolves references; the formats below decide how each $type is written per platform.
// Theme modes (light/dark) and accents become [data-theme] / [data-accent] selectors (DESIGN.md §9).

import StyleDictionary from 'style-dictionary';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { toCssLinear, toPhysics } from '@scyde/springs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const DEFAULT_ACCENT = 'ember'; // DESIGN.md v2 §2.2 (Island)
const HEADER = 'Generated by web/packages/tokens/build.mjs from design/tokens. Do not edit.';

// ---------- helpers ----------

const kebab = (parts) => parts.join('-').replace(/[^a-zA-Z0-9-]/g, '-');
const camel = (parts) =>
  parts
    .join('-')
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((p, i) => (i === 0 ? p.toLowerCase() : p[0].toUpperCase() + p.slice(1)))
    .join('');
const pascal = (parts) => {
  const c = camel(parts);
  return c[0].toUpperCase() + c.slice(1);
};

/** '#RRGGBB' | '#RRGGBBAA' -> {r,g,b,a} (0-255, a 0-1) */
function parseHex(hex) {
  const h = hex.replace('#', '');
  if (!/^([0-9a-f]{6}|[0-9a-f]{8})$/i.test(h)) throw new Error(`Unsupported colour ${hex}`);
  const n = (i) => parseInt(h.slice(i, i + 2), 16);
  return { r: n(0), g: n(2), b: n(4), a: h.length === 8 ? n(6) / 255 : 1 };
}
const cssColor = (hex) => {
  const { r, g, b, a } = parseHex(hex);
  return a === 1 ? hex.toUpperCase() : `rgb(${r} ${g} ${b} / ${+a.toFixed(3)})`;
};
const px = (v) => parseFloat(String(v));

function cssValue(token) {
  const v = token.$value;
  switch (token.$type) {
    case 'color':
      return cssColor(v);
    case 'cubicBezier':
      return `cubic-bezier(${v.join(', ')})`;
    case 'fontFamily':
      return v.map((f) => (/\s/.test(f) && !f.includes('-') ? `"${f}"` : /\s/.test(f) ? `"${f}"` : f)).join(', ');
    case 'shadow':
      return v
        .map((s) => `${s.inset ? 'inset ' : ''}${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${cssColor(s.color)}`)
        .join(', ');
    case 'x-conic-gradient':
      return `conic-gradient(from ${v.from}, ${v.stops.map(cssColor).join(', ')})`;
    case 'x-aura-mesh':
      return v
        .map((b) => `radial-gradient(circle at ${b.x} ${b.y}, ${cssColor(b.color)} 0, transparent ${b.size})`)
        .join(', ');
    default:
      return String(v);
  }
}

/** Splits tokens into primitives, per-theme semantics and accents. */
function classify(tokens) {
  const out = { primitives: [], themes: { light: [], dark: [] }, accents: {} };
  for (const t of tokens) {
    const [head, a, b, ...rest] = t.path;
    if (head === 'theme') out.themes[a].push({ ...t, name: kebab([b, ...rest]), local: [b, ...rest] });
    else if (head === 'accent') {
      out.accents[a] ??= { light: {}, dark: {} };
      out.accents[a][b][rest.join('-')] = t.$value;
    } else out.primitives.push({ ...t, name: kebab(t.path), local: t.path });
  }
  return out;
}

// ---------- CSS ----------

StyleDictionary.registerFormat({
  name: 'scyde/css',
  format: ({ dictionary }) => {
    const { primitives, themes, accents } = classify(dictionary.allTokens);
    const decl = (name, value) => `  --${name}: ${value};`;
    const lines = [`/* ${HEADER} */`, ''];

    const prim = [];
    for (const t of primitives) {
      if (t.$type === 'x-spring') {
        const { easing, duration } = toCssLinear(t.$value);
        prim.push(decl(t.name, easing), decl(`${t.name}-duration`, `${duration}ms`));
      } else if (t.path[0] === 'density') {
        // density handled below
      } else prim.push(decl(t.name, cssValue(t)));
    }
    prim.push(decl('density-scale', '1'), decl('motion-distance-scale', '1'));
    lines.push(':root {', ...prim, '}', '');

    const themeBlock = (mode) => [
      `  color-scheme: ${mode};`,
      ...themes[mode].map((t) => decl(t.name, cssValue(t))),
      ...accentDecls(accents[DEFAULT_ACCENT][mode]),
    ];
    const accentDecls = (a) => Object.entries(a).map(([k, v]) => decl(`accent-${k}`, cssColor(v)));

    lines.push(':root,', '[data-theme="light"] {', ...themeBlock('light'), '}', '');
    lines.push('[data-theme="dark"] {', ...themeBlock('dark'), '}', '');
    lines.push('@media (prefers-color-scheme: dark) {', '  :root:not([data-theme]) {', ...themeBlock('dark').map((l) => '  ' + l), '  }', '}', '');

    const names = Object.keys(accents);
    for (const n of names) lines.push(`[data-accent="${n}"] {`, ...accentDecls(accents[n].light), '}');
    lines.push('');
    for (const n of names) lines.push(`[data-theme="dark"][data-accent="${n}"] {`, ...accentDecls(accents[n].dark), '}');
    lines.push('@media (prefers-color-scheme: dark) {');
    for (const n of names)
      lines.push(`  :root:not([data-theme])[data-accent="${n}"] {`, ...accentDecls(accents[n].dark).map((l) => '  ' + l), '  }');
    lines.push('}', '');

    const compact = dictionary.allTokens.find((t) => t.path.join('.') === 'density.compact.scale').$value;
    lines.push(`[data-density="compact"] {`, decl('density-scale', compact), '}', '');

    const reduced = dictionary.allTokens.find((t) => t.path.join('.') === 'motion.duration.reduced').$value;
    const reducedDecls = [
      ...['instant', 'fast', 'base', 'slow', 'choreo-max'].map((d) => decl(`motion-duration-${d}`, reduced)),
      decl('motion-stagger-min', '0ms'),
      decl('motion-stagger-max', '0ms'),
      decl('motion-distance-scale', '0'),
    ];
    lines.push('[data-motion="reduced"] {', ...reducedDecls, '}');
    lines.push('@media (prefers-reduced-motion: reduce) {', '  :root:not([data-motion="full"]) {', ...reducedDecls.map((l) => '  ' + l), '  }', '}', '');

    lines.push('@media (prefers-contrast: more) {', '  :root {', '    --border-hairline: var(--border-strong);', '  }', '}', '');
    return lines.join('\n');
  },
});

// ---------- flat JSON (contrast-check, core/theme) ----------

StyleDictionary.registerFormat({
  name: 'scyde/json',
  format: ({ dictionary }) => {
    const out = {};
    for (const t of dictionary.allTokens) out[t.path.join('.')] = { type: t.$type, value: t.$value };
    return JSON.stringify(out, null, 2) + '\n';
  },
});

// ---------- native helpers ----------

function nativeEntries(tokens, lang) {
  // returns [{group, name, type, value}] for kinds that make sense natively
  const res = [];
  for (const t of tokens) {
    if (['shadow', 'x-aura-mesh', 'fontFamily'].includes(t.$type)) continue;
    res.push(t);
  }
  return res;
}

function kColor(hex) {
  const { r, g, b, a } = parseHex(hex);
  const h = (n) => n.toString(16).padStart(2, '0').toUpperCase();
  return `Color(0x${h(Math.round(a * 255))}${h(r)}${h(g)}${h(b)})`;
}
function sColor(hex) {
  const { r, g, b, a } = parseHex(hex);
  const f = (n) => +(n / 255).toFixed(4);
  return `Color(.sRGB, red: ${f(r)}, green: ${f(g)}, blue: ${f(b)}, opacity: ${+a.toFixed(4)})`;
}
const isTypeSize = (t) => t.path[0] === 'type' && (t.path.at(-1) === 'size' || t.path.at(-1) === 'line-height');
const isTracking = (t) => t.path.at(-1) === 'tracking';

function kotlinValue(t) {
  const v = t.$value;
  switch (t.$type) {
    case 'color':
      return kColor(v);
    case 'dimension':
      if (isTracking(t)) return `(${parseFloat(v)}f).em`;
      return isTypeSize(t) ? `${px(v)}.sp` : `${px(v)}.dp`;
    case 'duration':
      return `${parseInt(v, 10)}`;
    case 'cubicBezier':
      return `CubicBezierEasing(${v.map((n) => `${n}f`).join(', ')})`;
    case 'fontWeight':
      return `FontWeight(${v})`;
    case 'number':
      return `${v}f`;
    case 'x-spring': {
      const p = toPhysics(v);
      return `ScydeSpring(stiffness = ${p.stiffness.toFixed(2)}f, dampingRatio = ${p.dampingRatio}f)`;
    }
    case 'x-conic-gradient':
      return `listOf(${v.stops.map(kColor).join(', ')})`;
    default:
      return null;
  }
}

function swiftValue(t) {
  const v = t.$value;
  switch (t.$type) {
    case 'color':
      return sColor(v);
    case 'dimension':
      return isTracking(t) ? `CGFloat(${parseFloat(v)}) // em` : `CGFloat(${px(v)})`;
    case 'duration':
      return `TimeInterval(${parseInt(v, 10) / 1000})`;
    case 'cubicBezier':
      return `ScydeBezier(x1: ${v[0]}, y1: ${v[1]}, x2: ${v[2]}, y2: ${v[3]})`;
    case 'fontWeight':
      return { 400: 'Font.Weight.regular', 500: 'Font.Weight.medium', 600: 'Font.Weight.semibold' }[v];
    case 'number':
      return `${v}`;
    case 'x-spring':
      return `ScydeSpring(response: ${v.response}, dampingFraction: ${v.damping})`;
    case 'x-conic-gradient':
      return `[${v.stops.map(sColor).join(', ')}]`;
    default:
      return null;
  }
}

function groupBy(tokens, keyFn) {
  const m = new Map();
  for (const t of tokens) {
    const k = keyFn(t);
    if (!m.has(k)) m.set(k, []);
    m.get(k).push(t);
  }
  return m;
}

StyleDictionary.registerFormat({
  name: 'scyde/kotlin',
  format: ({ dictionary }) => {
    const { primitives, themes, accents } = classify(dictionary.allTokens);
    const L = [
      `// ${HEADER}`,
      'package dev.scyde.browser.theme',
      '',
      'import androidx.compose.animation.core.CubicBezierEasing',
      'import androidx.compose.ui.graphics.Color',
      'import androidx.compose.ui.text.font.FontWeight',
      'import androidx.compose.ui.unit.dp',
      'import androidx.compose.ui.unit.em',
      'import androidx.compose.ui.unit.sp',
      '',
      '/** Compose: spring(dampingRatio = dampingRatio, stiffness = stiffness). */',
      'data class ScydeSpring(val stiffness: Float, val dampingRatio: Float)',
      '',
      'data class ScydeAccent(val fill: Color, val ink: Color, val onFill: Color, val ring: Color)',
      '',
      'data class ScydeColors(',
    ];
    const themeProps = nativeEntries(themes.light).map((t) => camel(t.local));
    L.push(...themeProps.map((p) => `    val ${p}: Color,`), ')', '');
    for (const mode of ['light', 'dark']) {
      L.push(`val ScydeColors${pascal([mode])} = ScydeColors(`);
      for (const t of nativeEntries(themes[mode])) L.push(`    ${camel(t.local)} = ${kotlinValue(t)},`);
      L.push(')', '');
    }
    L.push('object ScydeAccents {');
    for (const [n, a] of Object.entries(accents))
      for (const mode of ['light', 'dark'])
        L.push(
          `    val ${camel([n, mode])} = ScydeAccent(fill = ${kColor(a[mode].fill)}, ink = ${kColor(a[mode].ink)}, onFill = ${kColor(a[mode]['on-fill'])}, ring = ${kColor(a[mode].ring)})`,
        );
    L.push('}', '');
    for (const [group, ts] of groupBy(nativeEntries(primitives), (t) => t.path[0])) {
      L.push(`object Scyde${pascal([group])} {`);
      for (const t of ts) {
        const val = kotlinValue(t);
        if (val == null) continue;
        let name = camel(t.local.slice(1));
        if (/^\d/.test(name)) name = `${group[0]}${name}`;
        const unit = t.$type === 'duration' ? ' // ms' : '';
        L.push(`    val ${name || camel(t.local)} = ${val}${unit}`);
      }
      L.push('}', '');
    }
    return L.join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'scyde/swift',
  format: ({ dictionary }) => {
    const { primitives, themes, accents } = classify(dictionary.allTokens);
    const L = [
      `// ${HEADER}`,
      'import SwiftUI',
      '',
      'public struct ScydeSpring: Sendable {',
      '    public let response: Double',
      '    public let dampingFraction: Double',
      '    public var animation: Animation { .spring(response: response, dampingFraction: dampingFraction) }',
      '}',
      '',
      'public struct ScydeBezier: Sendable {',
      '    public let x1: Double, y1: Double, x2: Double, y2: Double',
      '    public func animation(duration: TimeInterval) -> Animation { .timingCurve(x1, y1, x2, y2, duration: duration) }',
      '}',
      '',
      'public struct ScydeAccent: Sendable {',
      '    public let fill: Color',
      '    public let ink: Color',
      '    public let onFill: Color',
      '    public let ring: Color',
      '}',
      '',
      'public struct ScydeColors: Sendable {',
    ];
    const props = nativeEntries(themes.light).map((t) => camel(t.local));
    L.push(...props.map((p) => `    public let ${p}: Color`), '}', '');
    L.push('public extension ScydeColors {');
    for (const mode of ['light', 'dark']) {
      L.push(`    static let ${mode} = ScydeColors(`);
      const ents = nativeEntries(themes[mode]);
      ents.forEach((t, i) => L.push(`        ${camel(t.local)}: ${swiftValue(t)}${i < ents.length - 1 ? ',' : ''}`));
      L.push('    )');
    }
    L.push('}', '', 'public enum ScydeAccents {');
    for (const [n, a] of Object.entries(accents))
      for (const mode of ['light', 'dark'])
        L.push(
          `    public static let ${camel([n, mode])} = ScydeAccent(fill: ${sColor(a[mode].fill)}, ink: ${sColor(a[mode].ink)}, onFill: ${sColor(a[mode]['on-fill'])}, ring: ${sColor(a[mode].ring)})`,
        );
    L.push('}', '');
    for (const [group, ts] of groupBy(nativeEntries(primitives), (t) => t.path[0])) {
      L.push(`public enum Scyde${pascal([group])} {`);
      for (const t of ts) {
        const val = swiftValue(t);
        if (val == null) continue;
        let name = camel(t.local.slice(1));
        if (/^\d/.test(name)) name = `${group[0]}${name}`;
        L.push(`    public static let ${name || camel(t.local)} = ${val}`);
      }
      L.push('}', '');
    }
    return L.join('\n');
  },
});

